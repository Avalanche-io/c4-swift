// Generates Sources/C4M/PrintableTable.swift from the shared table
// Tests/C4MTests/SafeNameVector/printable-<version>.txt, a byte-for-byte copy
// of c4 core's c4m/testdata/safename-vector/printable-<version>.txt.
//
// Run from the repository root:
//
//     swift Scripts/gen_printable.swift
//
// SafeName's printable test is pinned to one Unicode version (decided
// 2026-11-13 by the release lead; reversible), so it never asks the runtime's
// Unicode tables. PrintableTableTests checks the generated table against the
// text file, range by range.

import Foundation

let version = String(
    decoding: FileManager.default.contents(atPath: "Tests/C4MTests/SafeNameVector/unicode-version.txt")!,
    as: UTF8.self
).trimmingCharacters(in: .whitespacesAndNewlines)
let input = "Tests/C4MTests/SafeNameVector/printable-\(version).txt"
let output = "Sources/C4M/PrintableTable.swift"

guard let data = FileManager.default.contents(atPath: input) else {
    FileHandle.standardError.write(Data("cannot read \(input)\n".utf8))
    exit(1)
}

var ranges: [(String, String)] = []
var previousHi: UInt32? = nil
for line in String(decoding: data, as: UTF8.self).split(separator: "\n") {
    if line.isEmpty || line.hasPrefix("#") { continue }
    let parts = line.components(separatedBy: "..")
    guard parts.count == 2, let lo = UInt32(parts[0], radix: 16), let hi = UInt32(parts[1], radix: 16), lo <= hi else {
        FileHandle.standardError.write(Data("bad line \(line)\n".utf8))
        exit(1)
    }
    if let p = previousHi, lo <= p {
        FileHandle.standardError.write(Data("ranges not sorted and disjoint at \(line)\n".utf8))
        exit(1)
    }
    previousHi = hi
    ranges.append((parts[0], parts[1]))
}

var out = """
// Code generated by Scripts/gen_printable.swift from
// Tests/C4MTests/SafeNameVector/printable-\(version).txt. DO NOT EDIT.

/// The Unicode version SafeName's printable test is pinned to.
let printableUnicodeVersion = "\(version)"

/// Code points SafeName writes as themselves (Tier 1): Go's unicode.IsPrint
/// at Unicode \(version), as inclusive ranges, sorted and disjoint.
let printableRanges: [(UInt32, UInt32)] = [

"""
for (lo, hi) in ranges {
    out += "    (0x\(lo), 0x\(hi)),\n"
}
out += "]\n"

try! Data(out.utf8).write(to: URL(fileURLWithPath: output))
print("wrote \(output): \(ranges.count) ranges, Unicode \(version)")
